// Copies the modules shared with the app (JPEG metadata stripping and AI response
// validation) into server/src/shared so the server deploys on its own.
// `npm test` fails if these copies drift from the app's versions.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..', '..');
export const SHARED = [
  ['src/services/jpeg.ts', 'server/src/shared/jpeg.ts'],
  ['src/recognition/validate.ts', 'server/src/shared/validate.ts'],
];
const HEADER = '// GENERATED by server/scripts/sync-shared.mjs from the app source. Do not edit here.\n';

export function transform(source) {
  // The server runs under Node's type stripping, which needs explicit .ts extensions.
  return HEADER + source.replace("from './types'", "from './types.ts'");
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  for (const [from, to] of SHARED) {
    writeFileSync(join(root, to), transform(readFileSync(join(root, from), 'utf8')));
    console.log(`synced ${from} -> ${to}`);
  }
}
