#!/usr/bin/env node
// Generates src/catalog/specs.data.ts from data/specs.json.
// Validates every record: it must belong to a catalog generation and cite at
// least one https source. Values are copied as stated; nothing is converted.
import { readFileSync, writeFileSync } from 'node:fs';

const root = new URL('..', import.meta.url);
const src = JSON.parse(readFileSync(new URL('data/specs.json', root), 'utf8'));
const catalogText = readFileSync(new URL('src/catalog/vehicles.ts', root), 'utf8');
const ids = new Set([...catalogText.matchAll(/\bv\(\s*'([^']+)'/g)].map((m) => m[1]));

const ASPIRATION = new Set(['NA', 'turbo', 'twin-turbo', 'supercharged', 'hybrid', 'electric', null]);
const errors = [];
const out = {};
for (const [id, r] of Object.entries(src.vehicles)) {
  if (!ids.has(id)) errors.push(`${id}: not a catalog vehicle id`);
  if (!r.sources?.length || !r.sources.every((s) => s.url?.startsWith('https://') && s.title)) {
    errors.push(`${id}: needs at least one https source with a title`);
  }
  for (const e of r.engines ?? []) {
    if (!ASPIRATION.has(e.aspiration ?? null)) errors.push(`${id}: bad aspiration ${e.aspiration}`);
  }
  out[id] = {
    chassis: r.chassis ?? null,
    bodyStyles: r.bodyStyles ?? [],
    layout: r.layout ?? null,
    drivetrains: r.drivetrains ?? [],
    engines: (r.engines ?? []).map((e) => ({
      name: e.name,
      configuration: e.configuration ?? null,
      displacementCc: e.displacementCc ?? null,
      aspiration: e.aspiration ?? null,
      powerHp: e.powerHp ?? null,
      powerKw: e.powerKw ?? null,
      torqueNm: e.torqueNm ?? null,
      note: e.note ?? null,
    })),
    transmissions: r.transmissions ?? [],
    performance: (r.performance ?? []).map((p) => ({ metric: p.metric, value: p.value, variant: p.variant ?? null })),
    sources: r.sources.map((s) => ({ title: s.title, url: s.url })),
  };
}
if (errors.length) {
  console.error(errors.join('\n'));
  process.exit(1);
}

const body = `// GENERATED by scripts/build-specs.mjs from data/specs.json. Do not edit by hand.
// Source text: Wikipedia, CC BY-SA 4.0. See docs/DATA_PROVENANCE.md.
import type { VehicleSpecs } from './specs';

export const SPEC_ACCESSED = ${JSON.stringify(src.accessed)};
export const SPECS: Record<string, VehicleSpecs> = ${JSON.stringify(out, null, 2)};
`;
writeFileSync(new URL('src/catalog/specs.data.ts', root), body);
console.log(`specs: ${Object.keys(out).length} generations written`);
